        if (last_srname /= expected_name) then
            print '(A,A,A,I0)', 'FAIL: expected srname "', expected_name, '" but got "', trim(last_srname), '"'
            stop 1
        end if
        if (last_info /= expected_code) then
            print '(A,A,A,I0,A,I0)', 'FAIL: expected info=', expected_name, ' but got info=', last_info
            stop 1
        end if
        print '(A,A,A,I0)', 'PASS: ', trim(expected_name), ' info=', last_info
    end subroutine check_error

