!> \brief Tests input validation (qrupdate_xerror) for all qrupdate functions.
program test_qrupdate_validation
    use iso_fortran_env
    use qrupdate_error
    use test_state
    implicit none

    integer, parameter :: n = 5
    external sch1dn, dch1dn, cch1dn, zch1dn
    external schdex, dchdex, cchdex, zchdex
    external schinx, dchinx, cchinx, zchinx
    external schshx, dchshx, cchshx, zchshx
    external slu1up, dlu1up, clu1up, zlu1up
    external slup1up, dlup1up, clup1up, zlup1up
    external sqr1up, dqr1up, cqr1up, zqr1up
    external sqrdec, dqrdec, cqrdec, zqrdec
    external sqrder, dqrder, cqrder, zqrder
    external sqrinc, dqrinc, cqrinc, zqrinc
    external sqrinr, dqrinr, cqrinr, zqrinr
    external sqrshc, dqrshc, cqrshc, zqrshc
    external sqrot, dqrot, cqrot, zqrot
    external sqhqr, dqhqr, cqhqr, zqhqr
    external sqrqh, dqrqh, cqrqh, zqrqh
    external sgqvec, dgqvec, cgqvec, zgqvec

    integer :: info
    real(real32) :: R_s(n,n), u_s(n), w_s(n), rw_s(n)
    real(real64) :: R_d(n,n), u_d(n), w_d(n), rw_d(n)
    complex(real32) :: R_c(n,n), u_c(n), rw_c(n)
    complex(real32) :: R_z(n,n), u_z(n), rw_z(n)
    real(real32) :: Q_s(n,n), c_s(n-1), s_s(n-1), rhs_s(n)
    real(real64) :: Q_d(n,n), c_d(n-1), s_d(n-1), rhs_d(n)
    complex(real32) :: Q_c(n,n), Q_z(n,n), rhs_c(n), rhs_z(n)
    real(real32) :: c_c(n-1), c_z(n-1)
    complex(real32) :: s_c(n-1), s_z(n-1)
    real(real32) :: L_s(n,n), v_s(n), wv_s(n)
    real(real64) :: L_d(n,n), v_d(n), wv_d(n)
    complex(real32) :: L_c(n,n), v_c(n), wv_c(n), L_z(n,n), v_z(n), wv_z(n)
    real(real32) :: p_s(n), p2_s(n)
    real(real64) :: p_d(n), p2_d(n)
    complex(real32) :: p_c(n), p2_c(n), p_z(n), p2_z(n)
    real(real32) :: x_s(n), x_d(n), x_c(n), x_z(n)
    character(len=1) :: dir

    print *, 'Testing input validation for all qrupdate functions...'

    ! Initialize arrays to avoid undefined values
    R_s = 0; u_s = 0; w_s = 0; rw_s = 0
    R_d = 0; u_d = 0; w_d = 0; rw_d = 0
    R_c = 0; u_c = 0; rw_c = 0
    R_z = 0; u_z = 0; rw_z = 0
    Q_s = 0; c_s = 0; s_s = 0; rhs_s = 0
    Q_d = 0; c_d = 0; s_d = 0; rhs_d = 0
    Q_c = 0; c_c = 0; s_c = 0; rhs_c = 0
    Q_z = 0; c_z = 0; s_z = 0; rhs_z = 0
    L_s = 0; v_s = 0; wv_s = 0
    L_d = 0; v_d = 0; wv_d = 0
    L_c = 0; v_c = 0; wv_c = 0
    L_z = 0; v_z = 0; wv_z = 0
    p_s = 0; p2_s = 0; p_d = 0; p2_d = 0
    p_c = 0; p2_c = 0; p_z = 0; p2_z = 0
    x_s = 0; x_d = 0; x_c = 0; x_z = 0

    ! ====== Cholesky downdate ======
    ! sch1dn(n,R,ldr,u,w,info): validates n>=0, ldr>=n (negates info before xerror)
    call reset()
    call sch1dn(-1, R_s, n, u_s, w_s, info)
    call check_error('SCH1DN', 1)
    call reset()
    call sch1dn(n, R_s, n-1, u_s, w_s, info)
    call check_error('SCH1DN', 3)
    call reset()
    call dch1dn(-1, R_d, n, u_d, w_d, info)
    call check_error('DCH1DN', 1)
    call reset()
    call dch1dn(n, R_d, n-1, u_d, w_d, info)
    call check_error('DCH1DN', 3)
    call reset()
    call cch1dn(-1, R_c, n, u_c, rw_c, info)
    call check_error('CCH1DN', 1)
    call reset()
    call cch1dn(n, R_c, n-1, u_c, rw_c, info)
    call check_error('CCH1DN', 3)
    call reset()
    call zch1dn(-1, R_z, n, u_z, rw_z, info)
    call check_error('ZCH1DN', 1)
    call reset()
    call zch1dn(n, R_z, n-1, u_z, rw_z, info)
    call check_error('ZCH1DN', 3)

    ! ====== Cholesky delete ======
    ! schdex(n,R,ldr,j,w): validates n>=0, j in [1,n]
    call reset()
    call schdex(-1, R_s, n, 1, w_s)
    call check_error('SCHDEX', 1)
    call reset()
    call schdex(n, R_s, n, 0, w_s)
    call check_error('SCHDEX', 4)
    call reset()
    call dchdex(-1, R_d, n, 1, w_d)
    call check_error('DCHDEX', 1)
    call reset()
    call dchdex(n, R_d, n, 0, w_d)
    call check_error('DCHDEX', 4)
    call reset()
    call cchdex(-1, R_c, n, 1, rw_c)
    call check_error('CCHDEX', 1)
    call reset()
    call cchdex(n, R_c, n, 0, rw_c)
    call check_error('CCHDEX', 4)
    call reset()
    call zchdex(-1, R_z, n, 1, rw_z)
    call check_error('ZCHDEX', 1)
    call reset()
    call zchdex(n, R_z, n, 0, rw_z)
    call check_error('ZCHDEX', 4)

    ! ====== Cholesky insert ======
    ! schinx(n,R,ldr,j,u,w,info): validates n>=0, j in [1,n+1] (passes info directly)
    ! dchinx uses -info before xerror, others pass info directly
    call reset()
    call schinx(-1, R_s, n, 1, u_s, w_s, info)
    call check_error('SCHINX', -1)
    call reset()
    call schinx(n, R_s, n, 0, u_s, w_s, info)
    call check_error('SCHINX', -4)
    call reset()
    call dchinx(-1, R_d, n, 1, u_d, w_d, info)
    call check_error('DCHINX', 1)
    call reset()
    call dchinx(n, R_d, n, 0, u_d, w_d, info)
    call check_error('DCHINX', 4)
    call reset()
    call cchinx(-1, R_c, n, 1, u_c, rw_c, info)
    call check_error('CCHINX', -1)
    call reset()
    call cchinx(n, R_c, n, 0, u_c, rw_c, info)
    call check_error('CCHINX', -4)
    call reset()
    call zchinx(-1, R_z, n, 1, u_z, rw_z, info)
    call check_error('ZCHINX', -1)
    call reset()
    call zchinx(n, R_z, n, 0, u_z, rw_z, info)
    call check_error('ZCHINX', -4)

    ! ====== Cholesky shift ======
    ! schshx(n,R,ldr,i,j,w): validates n>=0, i in [1,n], j in [1,n]
    call reset()
    call schshx(-1, R_s, n, 1, 1, w_s)
    call check_error('SCHSHX', 1)
    call reset()
    call schshx(n, R_s, n, 0, 1, w_s)
    call check_error('SCHSHX', 4)
    call reset()
    call schshx(n, R_s, n, 1, 0, w_s)
    call check_error('SCHSHX', 5)
    call reset()
    call dchshx(-1, R_d, n, 1, 1, w_d)
    call check_error('DCHSHX', 1)
    call reset()
    call dchshx(n, R_d, n, 0, 1, w_d)
    call check_error('DCHSHX', 4)
    call reset()
    call dchshx(n, R_d, n, 1, 0, w_d)
    call check_error('DCHSHX', 5)
    call reset()
    call cchshx(-1, R_c, n, 1, 1, rw_s, rw_c)
    call check_error('CCHSHX', 1)
    call reset()
    call cchshx(n, R_c, n, 0, 1, rw_s, rw_c)
    call check_error('CCHSHX', 4)
    call reset()
    call cchshx(n, R_c, n, 1, 0, rw_s, rw_c)
    call check_error('CCHSHX', 5)
    call reset()
    call zchshx(-1, R_z, n, 1, 1, rw_d, rw_z)
    call check_error('ZCHSHX', 1)
    call reset()
    call zchshx(n, R_z, n, 0, 1, rw_d, rw_z)
    call check_error('ZCHSHX', 4)
    call reset()
    call zchshx(n, R_z, n, 1, 0, rw_d, rw_z)
    call check_error('ZCHSHX', 5)

    ! ====== LU rank-1 update ======
    ! slu1up(m,n,L,ldl,R,ldr,u,v): validates m>=0, n>=0, ldl>=m, ldr>=min(m,n)
    call reset()
    call slu1up(-1, n, L_s, n, R_s, n, rhs_s, v_s)
    call check_error('SLU1UP', 1)
    call reset()
    call slu1up(n, -1, L_s, n, R_s, n, rhs_s, v_s)
    call check_error('SLU1UP', 2)
    call reset()
    call slu1up(n, n, L_s, n-1, R_s, n, rhs_s, v_s)
    call check_error('SLU1UP', 4)
    call reset()
    call slu1up(n, n, L_s, n, R_s, n-1, rhs_s, v_s)
    call check_error('SLU1UP', 6)
    call reset()
    call dlu1up(-1, n, L_d, n, R_d, n, rhs_d, v_d)
    call check_error('DLU1UP', 1)
    call reset()
    call dlu1up(n, -1, L_d, n, R_d, n, rhs_d, v_d)
    call check_error('DLU1UP', 2)
    call reset()
    call dlu1up(n, n, L_d, n-1, R_d, n, rhs_d, v_d)
    call check_error('DLU1UP', 4)
    call reset()
    call dlu1up(n, n, L_d, n, R_d, n-1, rhs_d, v_d)
    call check_error('DLU1UP', 6)
    call reset()
    call clu1up(-1, n, L_c, n, R_c, n, rhs_c, v_c)
    call check_error('CLU1UP', 1)
    call reset()
    call clu1up(n, -1, L_c, n, R_c, n, rhs_c, v_c)
    call check_error('CLU1UP', 2)
    call reset()
    call clu1up(n, n, L_c, n-1, R_c, n, rhs_c, v_c)
    call check_error('CLU1UP', 4)
    call reset()
    call clu1up(n, n, L_c, n, R_c, n-1, rhs_c, v_c)
    call check_error('CLU1UP', 6)
    call reset()
    call zlu1up(-1, n, L_z, n, R_z, n, rhs_z, v_z)
    call check_error('ZLU1UP', 1)
    call reset()
    call zlu1up(n, -1, L_z, n, R_z, n, rhs_z, v_z)
    call check_error('ZLU1UP', 2)
    call reset()
    call zlu1up(n, n, L_z, n-1, R_z, n, rhs_z, v_z)
    call check_error('ZLU1UP', 4)
    call reset()
    call zlu1up(n, n, L_z, n, R_z, n-1, rhs_z, v_z)
    call check_error('ZLU1UP', 6)

    ! ====== LU+perm rank-1 update ======
    ! slup1up(m,n,L,ldl,R,ldr,p,u,v,w): validates m>=0, n>=0, ldl>=m, ldr>=min(m,n)
    call reset()
    call slup1up(-1, n, L_s, n, R_s, n, p_s, rhs_s, v_s, wv_s)
    call check_error('SLUP1UP', 1)
    call reset()
    call slup1up(n, -1, L_s, n, R_s, n, p_s, rhs_s, v_s, wv_s)
    call check_error('SLUP1UP', 2)
    call reset()
    call slup1up(n, n, L_s, n-1, R_s, n, p_s, rhs_s, v_s, wv_s)
    call check_error('SLUP1UP', 4)
    call reset()
    call slup1up(n, n, L_s, n, R_s, n-1, p_s, rhs_s, v_s, wv_s)
    call check_error('SLUP1UP', 6)
    call reset()
    call dlup1up(-1, n, L_d, n, R_d, n, p_d, rhs_d, v_d, wv_d)
    call check_error('DLUP1UP', 1)
    call reset()
    call dlup1up(n, -1, L_d, n, R_d, n, p_d, rhs_d, v_d, wv_d)
    call check_error('DLUP1UP', 2)
    call reset()
    call dlup1up(n, n, L_d, n-1, R_d, n, p_d, rhs_d, v_d, wv_d)
    call check_error('DLUP1UP', 4)
    call reset()
    call dlup1up(n, n, L_d, n, R_d, n-1, p_d, rhs_d, v_d, wv_d)
    call check_error('DLUP1UP', 6)
    call reset()
    call clup1up(-1, n, L_c, n, R_c, n, p_c, rhs_c, v_c, wv_s)
    call check_error('CLUP1UP', 1)
    call reset()
    call clup1up(n, -1, L_c, n, R_c, n, p_c, rhs_c, v_c, wv_s)
    call check_error('CLUP1UP', 2)
    call reset()
    call clup1up(n, n, L_c, n-1, R_c, n, p_c, rhs_c, v_c, wv_s)
    call check_error('CLUP1UP', 4)
    call reset()
    call clup1up(n, n, L_c, n, R_c, n-1, p_c, rhs_c, v_c, wv_s)
    call check_error('CLUP1UP', 6)
    call reset()
    call zlup1up(-1, n, L_z, n, R_z, n, p_z, rhs_z, v_z, wv_d)
    call check_error('ZLUP1UP', 1)
    call reset()
    call zlup1up(n, -1, L_z, n, R_z, n, p_z, rhs_z, v_z, wv_d)
    call check_error('ZLUP1UP', 2)
    call reset()
    call zlup1up(n, n, L_z, n-1, R_z, n, p_z, rhs_z, v_z, wv_d)
    call check_error('ZLUP1UP', 4)
    call reset()
    call zlup1up(n, n, L_z, n, R_z, n-1, p_z, rhs_z, v_z, wv_d)
    call check_error('ZLUP1UP', 6)

    ! ====== QR rank-1 update ======
    ! sqr1up(m,n,k,Q,ldq,R,ldr,u,v,w): validates m>=0, n>=0, k valid, ldq>=m, ldr>=k
    call reset()
    call sqr1up(-1, n, n, Q_s, n, R_s, n, rhs_s, v_s, wv_s)
    call check_error('SQR1UP', 1)
    call reset()
    call sqr1up(n, -1, n, Q_s, n, R_s, n, rhs_s, v_s, wv_s)
    call check_error('SQR1UP', 2)
    call reset()
    call sqr1up(n, n, 99, Q_s, n, R_s, n, rhs_s, v_s, wv_s)
    call check_error('SQR1UP', 3)
    call reset()
    call sqr1up(n, n, n, Q_s, n-1, R_s, n, rhs_s, v_s, wv_s)
    call check_error('SQR1UP', 5)
    call reset()
    call sqr1up(n, n, n, Q_s, n, R_s, n-1, rhs_s, v_s, wv_s)
    call check_error('SQR1UP', 7)
    call reset()
    call dqr1up(-1, n, n, Q_d, n, R_d, n, rhs_d, v_d, wv_d)
    call check_error('DQR1UP', 1)
    call reset()
    call dqr1up(n, -1, n, Q_d, n, R_d, n, rhs_d, v_d, wv_d)
    call check_error('DQR1UP', 2)
    call reset()
    call dqr1up(n, n, 99, Q_d, n, R_d, n, rhs_d, v_d, wv_d)
    call check_error('DQR1UP', 3)
    call reset()
    call dqr1up(n, n, n, Q_d, n-1, R_d, n, rhs_d, v_d, wv_d)
    call check_error('DQR1UP', 5)
    call reset()
    call dqr1up(n, n, n, Q_d, n, R_d, n-1, rhs_d, v_d, wv_d)
    call check_error('DQR1UP', 7)
    call reset()
    call cqr1up(-1, n, n, Q_c, n, R_c, n, rhs_c, v_c, wv_s)
    call check_error('CQR1UP', 1)
    call reset()
    call cqr1up(n, -1, n, Q_c, n, R_c, n, rhs_c, v_c, wv_s)
    call check_error('CQR1UP', 2)
    call reset()
    call cqr1up(n, n, 99, Q_c, n, R_c, n, rhs_c, v_c, wv_s)
    call check_error('CQR1UP', 3)
    call reset()
    call cqr1up(n, n, n, Q_c, n-1, R_c, n, rhs_c, v_c, wv_s)
    call check_error('CQR1UP', 5)
    call reset()
    call cqr1up(n, n, n, Q_c, n, R_c, n-1, rhs_c, v_c, wv_s)
    call check_error('CQR1UP', 7)
    call reset()
    call zqr1up(-1, n, n, Q_z, n, R_z, n, rhs_z, v_z, wv_d)
    call check_error('ZQR1UP', 1)
    call reset()
    call zqr1up(n, -1, n, Q_z, n, R_z, n, rhs_z, v_z, wv_d)
    call check_error('ZQR1UP', 2)
    call reset()
    call zqr1up(n, n, 99, Q_z, n, R_z, n, rhs_z, v_z, wv_d)
    call check_error('ZQR1UP', 3)
    call reset()
    call zqr1up(n, n, n, Q_z, n-1, R_z, n, rhs_z, v_z, wv_d)
    call check_error('ZQR1UP', 5)
    call reset()
    call zqr1up(n, n, n, Q_z, n, R_z, n-1, rhs_z, v_z, wv_d)
    call check_error('ZQR1UP', 7)

    ! ====== QR delete (column) ======
    ! sqrdec(m,n,k,Q,ldq,R,ldr,j,w): validates m>=0, n>=0, k valid, ldq>=m, ldr>=k, j in [1,n+1]
    call reset()
    call sqrdec(-1, n, n, Q_s, n, R_s, n, 1, w_s)
    call check_error('SQRDEC', 1)
    call reset()
    call sqrdec(n, -1, n, Q_s, n, R_s, n, 1, w_s)
    call check_error('SQRDEC', 2)
    call reset()
    call sqrdec(n, n, 99, Q_s, n, R_s, n, 1, w_s)
    call check_error('SQRDEC', 3)
    call reset()
    call sqrdec(n, n, n, Q_s, n-1, R_s, n, 1, w_s)
    call check_error('SQRDEC', 5)
    call reset()
    call sqrdec(n, n, n, Q_s, n, R_s, n-1, 1, w_s)
    call check_error('SQRDEC', 7)
    call reset()
    call sqrdec(n, n, n, Q_s, n, R_s, n, 0, w_s)
    call check_error('SQRDEC', 8)
    call reset()
    call dqrdec(-1, n, n, Q_d, n, R_d, n, 1, w_d)
    call check_error('DQRDEC', 1)
    call reset()
    call dqrdec(n, -1, n, Q_d, n, R_d, n, 1, w_d)
    call check_error('DQRDEC', 2)
    call reset()
    call dqrdec(n, n, 99, Q_d, n, R_d, n, 1, w_d)
    call check_error('DQRDEC', 3)
    call reset()
    call dqrdec(n, n, n, Q_d, n-1, R_d, n, 1, w_d)
    call check_error('DQRDEC', 5)
    call reset()
    call dqrdec(n, n, n, Q_d, n, R_d, n-1, 1, w_d)
    call check_error('DQRDEC', 7)
    call reset()
    call dqrdec(n, n, n, Q_d, n, R_d, n, 0, w_d)
    call check_error('DQRDEC', 8)
    call reset()
    call cqrdec(-1, n, n, Q_c, n, R_c, n, 1, rw_c)
    call check_error('CQRDEC', 1)
    call reset()
    call cqrdec(n, -1, n, Q_c, n, R_c, n, 1, rw_c)
    call check_error('CQRDEC', 2)
    call reset()
    call cqrdec(n, n, 99, Q_c, n, R_c, n, 1, rw_c)
    call check_error('CQRDEC', 3)
    call reset()
    call cqrdec(n, n, n, Q_c, n-1, R_c, n, 1, rw_c)
    call check_error('CQRDEC', 5)
    call reset()
    call cqrdec(n, n, n, Q_c, n, R_c, n-1, 1, rw_c)
    call check_error('CQRDEC', 7)
    call reset()
    call cqrdec(n, n, n, Q_c, n, R_c, n, 0, rw_c)
    call check_error('CQRDEC', 8)
    call reset()
    call zqrdec(-1, n, n, Q_z, n, R_z, n, 1, rw_z)
    call check_error('ZQRDEC', 1)
    call reset()
    call zqrdec(n, -1, n, Q_z, n, R_z, n, 1, rw_z)
    call check_error('ZQRDEC', 2)
    call reset()
    call zqrdec(n, n, 99, Q_z, n, R_z, n, 1, rw_z)
    call check_error('ZQRDEC', 3)
    call reset()
    call zqrdec(n, n, n, Q_z, n-1, R_z, n, 1, rw_z)
    call check_error('ZQRDEC', 5)
    call reset()
    call zqrdec(n, n, n, Q_z, n, R_z, n-1, 1, rw_z)
    call check_error('ZQRDEC', 7)
